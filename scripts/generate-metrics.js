#!/usr/bin/env node
// Measures the characters of every built-in font stack in Chrome and writes src/metrics.js, the
// widths the library uses where there is no canvas to measure with (Node, the CLI, the HTTP API).
// Run it on a Mac (the stacks start with the macOS faces the styles were drawn with):
//
//   npm run metrics
import { writeFileSync } from 'node:fs';
import { chromium } from '@playwright/test';
import { FONTS } from '../src/text.js';
import { CHARS } from '../src/metrics.js';

const browser = await chromium.launch({ channel: process.env.CI ? undefined : 'chrome' });
const page = await browser.newPage();
await page.setContent('<!doctype html><title>metrics</title>');
const measured = await page.evaluate(
  ({ fonts, chars }) => {
    const ctx = /** @type {CanvasRenderingContext2D} */ (document.createElement('canvas').getContext('2d'));
    const size = 200;
    /** Widths in 1/200 em, as two hex digits each. @param {string} font */
    const table = (font) => {
      ctx.font = font;
      return [...chars]
        .map((ch) =>
          Math.min(255, Math.round(ctx.measureText(ch).width))
            .toString(16)
            .padStart(2, '0'),
        )
        .join('');
    };
    const sample = 'The Quick Brown Fox Jumps Over the Lazy Dog, MIDNIGHT ARITHMETIC 1984';
    /** @param {string} font */
    const width = (font) => {
      ctx.font = font;
      return ctx.measureText(sample).width;
    };
    return fonts.map(({ family }) => ({
      family,
      regular: table(`400 ${size}px ${family}`),
      bold: table(`700 ${size}px ${family}`),
      // Italics are a little narrower or wider as a whole: one factor for the font, the wider of
      // its two weights' (an estimate too wide shrinks the text a little; too narrow, it overflows).
      italic:
        Math.ceil(
          Math.max(
            width(`italic 400 ${size}px ${family}`) / width(`400 ${size}px ${family}`),
            width(`italic 700 ${size}px ${family}`) / width(`700 ${size}px ${family}`),
          ) * 1000,
        ) / 1000,
    }));
  },
  { fonts: Object.values(FONTS).filter((f) => !f.mono), chars: CHARS },
);
await browser.close();

const lines = measured.map(
  (m) =>
    `  [\n    ${JSON.stringify(m.family)},\n    { regular: '${m.regular}', bold: '${m.bold}', italic: ${m.italic} },\n  ],`,
);
writeFileSync(
  'src/metrics.js',
  `// Generated by scripts/generate-metrics.js (npm run metrics) from Chrome on macOS: each built-in
// font stack's character widths, for measuring text where there is no canvas (Node, the CLI, the
// HTTP API). Each table holds two hex digits per character of CHARS, in 1/200 em, at weights 400
// and 700; italic scales a font's widths.

/** The characters measured: printable ASCII, then common typographic marks and letters. */
export const CHARS =
  ${JSON.stringify(CHARS)};

/** @type {Map<string, { regular: string, bold: string, italic: number }>} */
export const METRICS = new Map([
${lines.join('\n')}
]);
`,
);
console.log(`Wrote src/metrics.js: ${measured.length} fonts, ${[...CHARS].length} characters each`);
