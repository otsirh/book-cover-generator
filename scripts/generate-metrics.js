#!/usr/bin/env node
// Measures the characters of every built-in font stack in Chrome and writes src/metrics.js, the
// widths the library uses where there is no canvas to measure with (Node, the CLI, the HTTP API).
// The stacks start with the macOS faces the styles were drawn with, so it runs on a Mac only:
//
//   npm run metrics
import { writeFileSync } from 'node:fs';
import { chromium } from '@playwright/test';
import { format, resolveConfig } from 'prettier';
import { FONTS } from '../src/text.js';
import { CHARS, UPRIGHT, ITALIC } from '../src/metrics.js';

if (process.platform !== 'darwin') {
  console.error('npm run metrics measures the macOS fonts the styles were drawn with: run it on a Mac');
  process.exit(1);
}

const browser = await chromium.launch({ channel: 'chrome' });
const page = await browser.newPage();
await page.setContent('<!doctype html><title>metrics</title>');
const measured = await page.evaluate(
  ({ fonts, chars, upright, italic }) => {
    const ctx = /** @type {CanvasRenderingContext2D} */ (document.createElement('canvas').getContext('2d'));
    /** Widths at 200 px, so in 1/200 em. @param {string} font */
    const table = (font) => {
      ctx.font = font;
      return [...chars].map((ch) => ctx.measureText(ch).width);
    };
    // (Each weight on its own: Chrome draws 600 with a bold face and 800 with a heavier one, where
    // the font has them, so widths don't follow from 400 and 700.)
    return fonts.map(({ family }) => ({
      family,
      upright: upright.map((w) => table(`${w} 200px ${family}`)),
      italic: italic.map((w) => table(`italic ${w} 200px ${family}`)),
    }));
  },
  { fonts: Object.values(FONTS).filter((f) => !f.mono), chars: CHARS, upright: UPRIGHT, italic: ITALIC },
);
await browser.close();

/**
 * Widths in 1/200 em as two hex digits each, rounded up: a little wide shrinks text a little, a
 * little narrow lets it overflow.
 * @param {number[]} widths @param {string} family
 */
function encode(widths, family) {
  return widths
    .map((w, i) => {
      const v = Math.ceil(w - 1e-6);
      if (v > 255)
        throw new Error(`${family}: "${[...CHARS][i]}" is ${(w / 200).toFixed(3)} em, wider than a table holds`);
      return v.toString(16).padStart(2, '0');
    })
    .join('');
}

const tables = measured.map((m) => {
  const upright = m.upright.map((t) => encode(t, m.family));
  const italic = m.italic.map((t) => encode(t, m.family));
  return `[${JSON.stringify(m.family)}, { upright: ${JSON.stringify(upright)}, italic: ${JSON.stringify(italic)} }],`;
});
const source = `// Generated by scripts/generate-metrics.js (npm run metrics) from Chrome on macOS: each built-in
// font stack's character widths, for measuring text where there is no canvas (Node, the CLI, the
// HTTP API). A table holds two hex digits per character of CHARS, in 1/200 em; there is one per
// weight in UPRIGHT, and italic ones per weight in ITALIC.

/** The characters measured: printable ASCII, then common typographic marks and letters. */
export const CHARS = ${JSON.stringify(CHARS)};
/** The weights measured upright, and in italics. */
export const UPRIGHT = ${JSON.stringify(UPRIGHT)};
export const ITALIC = ${JSON.stringify(ITALIC)};

/** @type {Map<string, { upright: string[], italic: string[] }>} */
export const METRICS = new Map([
${tables.join('\n')}
]);
`;
const file = 'src/metrics.js';
writeFileSync(file, await format(source, { ...(await resolveConfig(file)), filepath: file }));
console.log(
  `Wrote ${file}: ${measured.length} fonts, ${[...CHARS].length} characters, ${UPRIGHT.length + ITALIC.length} tables each`,
);
